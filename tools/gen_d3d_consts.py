"""Extract the numeric D3D9 / DirectInput / DirectSound constants (enums and simple #defines) into rt/dx_consts.h."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HEADERS = os.path.join(HERE, "..", "ref", "headers")
OUT = os.path.join(HERE, "..", "rt", "dx_consts.h")
PREFIX = re.compile(r"^(D3D|DI|DIK_|DSB|DSERR|DS_|DSSCL|DSBCAPS|DSBPLAY|DSBSTATUS|DISCL|DIDF|DIPROP|DIERR|DI_|DIJOFS|DIDFT|DIEDFL|DIDEVTYPE|DI8DEVTYPE)")


def fourcc(s):
    return ord(s[0]) | (ord(s[1]) << 8) | (ord(s[2]) << 16) | (ord(s[3]) << 24)


def main():
    out = {}
    for hdr in ("d3d9types.h", "d3d9caps.h", "d3d9.h", "dinput.h", "dsound.h"):
        text = open(os.path.join(HEADERS, hdr), encoding="latin1").read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        text = re.sub(r"MAKEFOURCC\('(.)',\s*'(.)',\s*'(.)',\s*'(.)'\)", lambda m: str(fourcc("".join(m.groups()))), text)
        text = re.sub(r"__MSABI_LONG\(([^)]*)\)", r"\1", text)
        text = re.sub(r"D3DTS_WORLDMATRIX\((\d+)\)", lambda m: str(256 + int(m.group(1))), text)
        for m in re.finditer(r"typedef\s+enum\s+\w*\s*\{(.*?)\}", text, re.S):
            last = -1
            for item in m.group(1).split(","):
                item = item.strip()
                if not item:
                    continue
                if "=" in item:
                    name, val = [x.strip() for x in item.split("=", 1)]
                    mm = re.match(r"MAKEFOURCC\('(.)',\s*'(.)',\s*'(.)',\s*'(.)'\)", val)
                    if mm:
                        v = fourcc("".join(mm.groups()))
                    else:
                        try:
                            v = int(eval(re.sub(r"(\d)[uUlL]+\b", r"\1", val), {}, dict(out)))
                        except Exception:  # noqa: BLE001
                            continue
                else:
                    name, v = item, last + 1
                if re.match(r"^\w+$", name):
                    out[name] = v & 0xFFFFFFFF
                    last = v
        for m in re.finditer(r"^\s*#define\s+(\w+)\s+(.+)$", text, re.M):
            name, val = m.group(1), m.group(2).strip()
            if not PREFIX.match(name) or name in out:
                continue
            try:
                v = int(eval(re.sub(r"(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", val), {}, dict(out)))
            except Exception:  # noqa: BLE001
                continue
            out[name] = v & 0xFFFFFFFF
    L = ["/* GENERATED by tools/gen_d3d_consts.py from the mingw-w64 DirectX headers -- do not edit. */", "#ifndef TMNT_DX_CONSTS_H", "#define TMNT_DX_CONSTS_H"]
    L.extend("#define %s 0x%08xU" % (k, v) for k, v in sorted(out.items()))
    L.append("#endif")
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(len(out), "constants")


if __name__ == "__main__":
    sys.exit(main())
