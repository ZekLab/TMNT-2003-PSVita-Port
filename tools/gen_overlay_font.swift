// Generates rt/overlay_font.h: an 8-bit alpha atlas of ASCII 32..126 plus the four PlayStation face button symbols
// (cross, circle, square, triangle), rendered with the system's fonts. Run: swift tools/gen_overlay_font.swift > rt/overlay_font.h
import AppKit

let cellW = 16, cellH = 22, cols = 16
var glyphs: [String] = (32...126).map { String(UnicodeScalar(UInt8($0))) }
glyphs += ["\u{2715}", "\u{25EF}", "\u{25A1}", "\u{25B3}"]   // ✕ ◯ □ △
let rows = (glyphs.count + cols - 1) / cols
let W = cellW * cols, H = cellH * rows

let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: W, pixelsHigh: H, bitsPerSample: 8, samplesPerPixel: 4,
                           hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: W * 4, bitsPerPixel: 32)!
NSGraphicsContext.saveGraphicsState()
NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
let text = NSFont(name: "Menlo-Bold", size: 15)!
let symbol = NSFont(name: "Apple Symbols", size: 17) ?? NSFont.systemFont(ofSize: 16)
for (i, g) in glyphs.enumerated() {
    let x = (i % cols) * cellW, y = H - (i / cols + 1) * cellH
    let font = i >= 95 ? symbol : text
    let attrs: [NSAttributedString.Key: Any] = [.font: font, .foregroundColor: NSColor.white]
    let s = NSAttributedString(string: g, attributes: attrs)
    let size = s.size()
    s.draw(at: NSPoint(x: CGFloat(x) + (CGFloat(cellW) - size.width) / 2, y: CGFloat(y) + (CGFloat(cellH) - size.height) / 2))
}
NSGraphicsContext.restoreGraphicsState()

print("/* GENERATED by tools/gen_overlay_font.swift -- do not edit. Alpha atlas: \(cols)x\(rows) cells of \(cellW)x\(cellH),")
print(" * glyph i = ASCII 32 + i for i < 95, then 95 cross, 96 circle, 97 square, 98 triangle. */")
print("#define OVL_FONT_W \(W)\n#define OVL_FONT_H \(H)\n#define OVL_CELL_W \(cellW)\n#define OVL_CELL_H \(cellH)\n#define OVL_COLS \(cols)")
print("static const unsigned char ovl_font[OVL_FONT_W * OVL_FONT_H] = {")
var line = ""
for y in 0..<H {
    for x in 0..<W {
        let a = rep.colorAt(x: x, y: y)!.alphaComponent
        line += "\(Int((a * 255).rounded())),"
        if line.count > 110 { print(line); line = "" }
    }
}
if !line.isEmpty { print(line) }
print("};")
