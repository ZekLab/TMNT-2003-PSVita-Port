"""Parse DECLARE_INTERFACE_ blocks of the mingw-w64 DirectX headers into rt/com_tables.h: per interface, method names in vtable order and stdcall argument counts (this included)."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HEADERS = os.path.join(HERE, "..", "ref", "headers")
OUT = os.path.join(HERE, "..", "rt", "com_tables.h")
WANT = {
    "d3d9.h": ["IDirect3D9", "IDirect3DDevice9", "IDirect3DSwapChain9", "IDirect3DResource9", "IDirect3DVertexDeclaration9",
               "IDirect3DVertexShader9", "IDirect3DPixelShader9", "IDirect3DBaseTexture9", "IDirect3DTexture9",
               "IDirect3DVolumeTexture9", "IDirect3DCubeTexture9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9",
               "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DQuery9", "IDirect3DStateBlock9"],
    "dinput.h": ["IDirectInput8A", "IDirectInputDevice8A"],
    "dsound.h": ["IDirectSound", "IDirectSoundBuffer", "IDirectSound3DListener", "IDirectSound3DBuffer", "IDirectSoundNotify"],
}


def parse(path, names):
    text = open(path, encoding="latin1").read()
    out = {}
    for m in re.finditer(r"DECLARE_INTERFACE_\((\w+)\s*,\s*(\w+)\)\s*\{(.*?)\};", text, re.S):
        name, body = m.group(1), m.group(3)
        if name not in names or name in out:
            continue
        flat = re.sub(r"\s+", " ", body)
        methods = []
        for mm in re.finditer(r"STDMETHOD_?\((?:[^,()]+,\s*)?(\w+)\)\s*\(([^)]*)\)\s*PURE;", flat):
            meth, args = mm.group(1), mm.group(2).strip()
            n = 1 if args == "THIS" else args.count(",") + 2
            methods.append((meth, n))
        out[name] = methods
    return out


def main():
    L = ["/* GENERATED by tools/gen_com_tables.py from the mingw-w64 DirectX headers -- do not edit. */", "#ifndef TMNT_COM_TABLES_H", "#define TMNT_COM_TABLES_H", "",
         "typedef struct { const char *name; int nargs; } com_method_info;", ""]
    for hdr, names in WANT.items():
        found = parse(os.path.join(HEADERS, hdr), set(names))
        for n in names:
            ms = found.get(n)
            if not ms:
                print("missing", n)
                continue
            L.append("static const com_method_info %s_methods[] = {" % n)
            L.extend('    { "%s", %d },' % m for m in ms)
            L.append("};")
            L.append("#define %s_COUNT %d" % (n, len(ms)))
            L.append("")
            print("%-30s %3d methods" % (n, len(ms)))
    L.append("#endif")
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main())
