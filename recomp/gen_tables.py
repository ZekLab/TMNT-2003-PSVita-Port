"""Runtime inputs: out/image.bin (the PE laid out by RVA), out/c/dispatch.c (RVA -> translated function) and out/c/imports.c (IAT slots)."""
import json
import os
import sys

import pefile
import tmnt_image as TI

OUT = os.path.join(os.path.dirname(__file__), "out")


def main():
    img = TI.TmntImage()
    with open(os.path.join(OUT, "image.bin"), "wb") as f:
        f.write(img.mem)
    with open(os.path.join(OUT, "functions.json")) as f:
        funcs = [fn["rva"] for fn in json.load(f)["functions"]]
    funcs.sort()
    L = ["/* GENERATED by recomp/gen_tables.py -- do not edit. */", "#include \"guest.h\"", ""]
    L.extend("void sub_%08x(CPU *__restrict c);" % r for r in funcs)
    L.append("const uint32_t guest_func_rvas[] = {")
    L.extend("    0x%08xU," % r for r in funcs)
    L.append("};")
    L.append("const guest_fn guest_func_ptrs[] = {")
    L.extend("    sub_%08x," % r for r in funcs)
    L.append("};")
    L.append("const uint32_t guest_func_count = %d;" % len(funcs))
    L.append("const uint32_t guest_image_entry = 0x%08xU;" % img.entry)
    L.append("const uint32_t guest_image_size = 0x%08xU;" % img.size)
    with open(os.path.join(OUT, "c", "dispatch.c"), "w") as f:
        f.write("\n".join(L) + "\n")

    pe = pefile.PE(TI.EXE)
    imps = []
    for e in pe.DIRECTORY_ENTRY_IMPORT:
        dll = e.dll.decode().upper().replace(".DLL", "")
        for i in e.imports:
            name = i.name.decode() if i.name else "#%d" % i.ordinal
            imps.append((i.address - pe.OPTIONAL_HEADER.ImageBase, "%s!%s" % (dll, name)))
    L = ["/* GENERATED by recomp/gen_tables.py -- do not edit. */", "#include <stdint.h>", "",
         "typedef struct { uint32_t slot_rva; const char *name; } guest_import_slot;",
         "const guest_import_slot guest_import_slots[] = {"]
    L.extend("    { 0x%08xU, \"%s\" }," % (r, n) for r, n in imps)
    L.append("};")
    L.append("const uint32_t guest_import_count = %d;" % len(imps))
    with open(os.path.join(OUT, "c", "imports.c"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("image %d bytes, %d functions, %d imports" % (len(img.mem), len(funcs), len(imps)))


if __name__ == "__main__":
    sys.exit(main())
